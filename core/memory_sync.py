#!/usr/bin/env python3
"""
Sync layer from SQLite to the native Claude Code memory.

Projects the data of ``alfred-memory.db`` to ``.md`` files in the native
Claude Code format (YAML frontmatter with name/description/type + content).
SQLite is the source of truth. The ``.md`` files are read-only projections
that Claude loads automatically in each conversation.

The sync is one-way (SQLite -> .md) and never changes the database. The
generated files carry the key ``source: alfred-memory`` in their frontmatter.
This key separates them from memories that the user writes by hand.

Usage:
    - From Python: create ``MemorySync`` with a ``MemoryDB`` and a memory
      directory, then call ``sync_all()`` or the incremental methods.
    - From shell: ``python3 core/memory_sync.py --action sync_all
      --project-dir /path/to/project``.

Main components:
    - ``resolve_memory_dir()``: finds the native memory directory.
    - ``MemorySync``: class that runs the data projection.

Error policy:
    Fail-open. No write error blocks the flow or raises an exception to the
    caller. Problems go to stderr with the ``[memory-sync]`` prefix.
"""

import json
import os
import re
import sys
from typing import Any, Dict, List, Optional, Tuple

