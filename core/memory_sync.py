# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

# Markers that delimit the managed section in MEMORY.md.
# The content between these markers is rebuilt on each sync.
# Content outside them is never changed.
_SYNC_START = "<!-- ALFRED-SYNC:START -->"
_SYNC_END = "<!-- ALFRED-SYNC:END -->"

# Prefix of the generated files. It identifies them for cleanup without
# reading the frontmatter of each file.
_FILE_PREFIX = "alfred-"

# YAML frontmatter key that marks files generated by this module.
# Only files with this key are changed or deleted.
_SOURCE_KEY = "alfred-memory"

# Prefix for log messages on stderr.
_LOG_PREFIX = "[memory-sync]"


# ---------------------------------------------------------------------------
# Path resolution
# ---------------------------------------------------------------------------

def resolve_memory_dir(
    project_dir: str,
    projects_base: Optional[str] = None,
) -> Optional[str]:
    """
    Find the native Claude Code memory directory for a project.

    Claude Code stores the memory of each project in a directory whose name
    is the absolute project path with slashes (``/``) replaced by hyphens
    (``-``). This function finds that directory inside the Claude Code
    projects base.

    Args:
        project_dir: absolute path of the current project.
        projects_base: path to the ``~/.claude/projects/`` directory. If not
            given, it is computed from ``$HOME``.

    Returns:
        Absolute path to the ``memory/`` directory. If the project directory
        or the ``memory/`` subdirectory does not exist, it is created.
        Returns ``None`` only if the creation fails.
    """
    if projects_base is None:
        home = os.path.expanduser("~")
        projects_base = os.path.join(home, ".claude", "projects")

    # Claude Code convention: the absolute path with / -> -
    # Example: /Users/foo/project -> -Users-foo-project
    normalized = project_dir.replace(os.sep, "-")
    if not normalized.startswith("-"):
        normalized = "-" + normalized

    memory_path = os.path.join(projects_base, normalized, "memory")

    # Create the full path if it does not exist. This covers three cases:
    # 1. ~/.claude/projects/ does not exist (new project with no memories)
    # 2. The project directory exists but has no memory/
    # 3. Everything exists (usual case, makedirs does nothing)
    try:
        os.makedirs(memory_path, exist_ok=True)
        return memory_path
    except OSError as e:
        _log(f"Cannot create the native memory directory: {e}")
        return None


