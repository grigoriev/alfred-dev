if __name__ == "__main__":
    """Run the sync from shell (session-start.sh).

    Usage::

        python3 core/memory_sync.py --action sync_all --project-dir /path

    The process always exits with code 0 (fail-open), so a failure does not
    block the session start.
    """
    import argparse

    parser = argparse.ArgumentParser(
        description="Sync SQLite memory to native .md files"
    )
    parser.add_argument(
        "--action", required=True, choices=["sync_all"],
        help="Action to run",
    )
    parser.add_argument(
        "--project-dir", required=True,
        help="Absolute path of the project directory",
    )
    parser.add_argument(
        "--commits-limit", type=int, default=10,
        help="Number of recent commits to project",
    )
    args = parser.parse_args()

    # Resolve paths
    db_path = os.path.join(args.project_dir, ".claude", "alfred-memory.db")
    if not os.path.isfile(db_path):
        sys.exit(0)

    memory_dir = resolve_memory_dir(args.project_dir)
    if memory_dir is None:
        _log("Native memory directory not found")
        sys.exit(0)

    try:
        # Adjust sys.path to import MemoryDB in standalone mode
        core_dir = os.path.dirname(os.path.abspath(__file__))
        parent_dir = os.path.dirname(core_dir)
        if parent_dir not in sys.path:
            sys.path.insert(0, parent_dir)

        from core.memory import MemoryDB as _MemoryDB

        commits_limit = args.commits_limit
        if load_memory_config is not None:
            project_config = load_memory_config(args.project_dir)
            configured_limit = project_config.get("sync_commits_limit")
            if isinstance(configured_limit, int) and configured_limit > 0:
                commits_limit = configured_limit

        db = _MemoryDB(db_path)
        sync = MemorySync(db, memory_dir, commits_limit=commits_limit)

        if args.action == "sync_all":
            result = sync.sync_all()
            _log(
                f"sync_all: {result['synced']} blocks synced, "
                f"{result['deleted']} deleted, "
                f"{result['errors']} errors"
            )

        db.close()
    except Exception as e:
        _log(f"Error: {e}")
        sys.exit(0)  # fail-open: never block the start
