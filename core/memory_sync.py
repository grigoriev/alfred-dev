def _frontmatter(
    name: str,
    description: str,
    source_id: Optional[int] = None,
) -> str:
    """
    Build the YAML frontmatter block for a native memory file.

    The format follows the Claude Code convention: the ``name``,
    ``description`` and ``type`` fields are required. The ``source`` and
    ``source_id`` fields are Alfred extensions that identify generated
    files.

    Args:
        name: visible name of the memory.
        description: short description (used to decide relevance).
        source_id: ID of the entity in SQLite, if any.

    Returns:
        Full YAML frontmatter block with ``---`` delimiters.
    """
    # Frontmatter scalars must stay on one line, so line breaks or repeated
    # spaces in the source content do not break the YAML.
    name = re.sub(r"\s+", " ", name).strip().replace('"', '\\"')
    description = re.sub(r"\s+", " ", description).strip().replace('"', '\\"')

    lines = [
        "---",
        f'name: "{name}"',
        f'description: "{description}"',
        "type: project",
        f"source: {_SOURCE_KEY}",
    ]
    if source_id is not None:
        lines.append(f"source_id: {source_id}")
    lines.append("---\n")
    return "\n".join(lines)


def _single_line_text(value: Any) -> str:
    """Normalize free text to one readable line."""
    return re.sub(r"\s+", " ", str(value or "")).strip()


def _markdown_table_cell(value: Any) -> str:
    """Escape Markdown table cells so pipes or line breaks do not break them."""
    text = _single_line_text(value)
    return text.replace("|", r"\|")


def _safe_write(path: str, content: str) -> bool:
    """
    Write a file safely, without raising exceptions.

    Creates the parent directories if they do not exist. If the write fails
    for any reason (permissions, full disk, etc.), logs a warning to stderr
    and returns ``False``.

    Args:
        path: absolute path of the file to write.
        content: full content of the file.

    Returns:
        ``True`` if the write succeeded, ``False`` otherwise.
    """
    try:
        parent = os.path.dirname(path)
        os.makedirs(parent, exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write(content)
        return True
    except OSError as e:
        _log(f"Cannot write {path}: {e}")
        return False


def _safe_delete(path: str) -> bool:
    """
    Delete a file safely, without raising exceptions.

    Args:
        path: absolute path of the file to delete.

    Returns:
        ``True`` if the file was deleted, ``False`` if it did not exist
        or could not be deleted.
    """
    try:
        if os.path.isfile(path):
            os.remove(path)
            return True
    except OSError as e:
        _log(f"Cannot delete {path}: {e}")
    return False


def _is_alfred_file(path: str) -> bool:
    """
    Check if this module generated a file.

    Looks for the ``source: alfred-memory`` key in the first 10 lines of the
    file (the frontmatter area).

    Args:
        path: absolute path of the file to check.

    Returns:
        ``True`` if the file contains the Alfred source mark.
    """
    try:
        with open(path, "r", encoding="utf-8") as f:
            for i, line in enumerate(f):
                if i > 10:
                    break
                if f"source: {_SOURCE_KEY}" in line:
                    return True
    except OSError:
        pass
    return False


def _read_frontmatter_field(path: str, field: str) -> Optional[str]:
    """
    Read one field from the YAML frontmatter of a file.

    Light parsing with no external dependencies: looks for the
    ``field: value`` pattern between the ``---`` delimiters.

    Args:
        path: absolute path of the file.
        field: name of the field to read.

    Returns:
        Field value (without quotes) or ``None`` if not found.
    """
    try:
        with open(path, "r", encoding="utf-8") as f:
            in_frontmatter = False
            for line in f:
                stripped = line.strip()
                if stripped == "---":
                    if in_frontmatter:
                        break
                    in_frontmatter = True
                    continue
                if in_frontmatter and stripped.startswith(f"{field}:"):
                    value = stripped[len(field) + 1:].strip()
                    if value.startswith('"') and value.endswith('"'):
                        value = value[1:-1]
                    return value
    except OSError:
        pass
    return None


def _count_archived(path: str) -> int:
    """
    Count the decisions in the consolidated archive file.

    Looks for headings with the ``## D#`` pattern that mark each archived
    decision.

    Args:
        path: path to the ``alfred-decisions-archived.md`` file.

    Returns:
        Number of decisions found.
    """
    try:
        with open(path, "r", encoding="utf-8") as f:
            content = f.read()
        return content.count("## D#")
    except OSError:
        return 0


def _log(msg: str) -> None:
    """Print a warning message to stderr with an identifying prefix."""
    print(f"{_LOG_PREFIX} {msg}", file=sys.stderr)


