# Main class
# ---------------------------------------------------------------------------

class MemorySync:
    """
    Project data from ``alfred-memory.db`` to native ``.md`` files.

    Reads from a ``MemoryDB`` instance (without changing it) and writes
    Markdown files with YAML frontmatter to the native memory directory. The
    generated files carry ``source: alfred-memory`` in the frontmatter to
    separate them from the manual memories of the user.

    Error policy: fail-open. No write error blocks the flow or raises an
    exception to the caller. Problems go to stderr with the
    ``[memory-sync]`` prefix.

    Args:
        db: connected ``MemoryDB`` instance (read only).
        memory_dir: absolute path to the Claude Code ``memory/`` directory.
        commits_limit: maximum number of recent commits to project.
    """

    def __init__(
        self,
        db: "MemoryDB",
        memory_dir: str,
        commits_limit: int = 10,
    ) -> None:
        self._db = db
        self._memory_dir = memory_dir
        self._commits_limit = commits_limit

    # --- Full sync ----------------------------------------------------------

    def sync_all(self) -> Dict[str, Any]:
        """
        Rebuild all projections from scratch.

        Runs the full sync: active decisions, decision archive, active
        iteration, recent commits, narrative summary and the MEMORY.md
        index. Removes orphan files at the end.

        Returns:
            Dictionary with counters of written files, deleted files and
            errors found during the sync.
        """
        result: Dict[str, Any] = {"synced": 0, "deleted": 0, "errors": 0}

        for method in (
            self._sync_decisions,
            self._sync_archived,
            self.sync_iteration,
            self.sync_commits,
            self.sync_summary,
        ):
            try:
                method()
                result["synced"] += 1
            except Exception as e:
                _log(f"Error in {method.__name__}: {e}")
                result["errors"] += 1

        deleted = self.cleanup_stale()
        result["deleted"] = len(deleted)

        try:
            self.update_index()
        except Exception as e:
            _log(f"Error while updating the index: {e}")
            result["errors"] += 1

        return result

    # --- Incremental sync ---------------------------------------------------

    def sync_decision(self, decision_id: int) -> None:
        """
        Project one decision.

        If the decision is active, write or update its own file. If it is not
        active, delete its own file and rebuild the consolidated archive of
        archived decisions.

        Args:
            decision_id: ID of the decision to sync.
        """
        decision = self._db.get_decision(decision_id)

        if decision is None:
            return

        if decision.get("status", "active") == "active":
            self._write_decision_file(decision)
        else:
            # Delete the decision file if it exists
            path = self._decision_path(decision_id)
            _safe_delete(path)
            # Rebuild the consolidated archive
            self._sync_archived()

    def sync_iteration(self) -> None:
        """Project the state of the active iteration.

        If the DB has an active iteration, write a file with the command,
        description, current phase and the table of completed phases.
        If there is no active iteration, delete the file if it exists.
        """
        active = self._db.get_active_iteration()
        path = os.path.join(self._memory_dir, "alfred-iteration-active.md")

        if active is None:
            _safe_delete(path)
            return

        # Get all completed phases without the general timeline limit and
        # without noise from other event types.
        phase_total = self._db.count_events(
            iteration_id=active["id"],
            event_type="phase_completed",
        )
        events = self._db.get_events(
            iteration_id=active["id"],
            event_type="phase_completed",
            ascending=True,
            limit=max(phase_total, 1),
        )
        phases: List[Dict[str, str]] = []
        for ev in events:
            payload: Dict[str, Any] = {}
            payload_raw = ev.get("payload")
            if payload_raw:
                try:
                    payload = (
                        json.loads(payload_raw)
                        if isinstance(payload_raw, str)
                        else payload_raw
                    )
                except (json.JSONDecodeError, AttributeError):
                    payload = {}

            phase_name = (
                str(payload.get("fase", "")).strip()
                or str(ev.get("phase", "")).strip()
            )
            if not phase_name:
                continue

            result = str(payload.get("resultado", "")).strip() or "aprobado"
            completed_at = (
                str(payload.get("completada_en", "")).strip()
                or str(ev.get("created_at", "")).strip()
            )
            phases.append({
                "nombre": phase_name,
                "resultado": result,
                "fecha": completed_at[:10],
            })

        # Find the current phase for the description
        fase_actual = "в процессе"
        if phases:
            fase_actual = f"после {phases[-1]['nombre']}"

        command = active.get("command", "неизвестно")
        description = active.get("description", "")
        started = active.get("started_at", "")[:10]

        content = _frontmatter(
            name=f"Активная итерация: {command} #{active['id']}",
            description=f"{description} -- текущая фаза: {fase_actual}",
        )
        content += f"\n**Команда:** {command}\n"
        content += f"**Описание:** {description}\n"
        content += f"**Статус:** активна с {started}\n"
        content += f"**Текущая фаза:** {fase_actual}\n"

        if phases:
            content += "\n### Завершённые фазы\n\n"
            content += "| Фаза | Результат | Дата |\n"
            content += "|------|-----------|-------|\n"
            for p in phases:
                content += (
                    f"| {_markdown_table_cell(p['nombre'])} | "
                    f"{_markdown_table_cell(p['resultado'])} | "
                    f"{_markdown_table_cell(p['fecha'])} |\n"
                )

        _safe_write(path, content)

    def sync_commits(self, limit: Optional[int] = None) -> None:
        """
        Project the most recent commits to a table file.

        Args:
            limit: number of commits to project. If not given, use the value
                set in the constructor.
        """
        if limit is None:
            limit = self._commits_limit

        path = os.path.join(self._memory_dir, "alfred-commits-recent.md")

        # Get recent commits through MemoryDB.get_commits with a global
        # limit. Errors are logged and produce an empty list.
        try:
            rows = self._db.get_commits(limit=limit)
        except Exception as e:
            _log(f"Error while reading commits: {e}")
            rows = []

        if not rows:
            _safe_delete(path)
            return

        content = _frontmatter(
            name="Последние записанные commits",
            description=(
                f"Последние commits в памяти ({limit}), "
                f"включая активный процесс и импортированную историю"
            ),
        )
        content += "\n| SHA | Сообщение | Автор | Дата | Контекст | Файлы |\n"
        content += "|-----|---------|-------|-------|----------|----------|\n"
        for row in rows:
            sha_short = row["sha"][:7] if row["sha"] else "?"
            msg = _markdown_table_cell(row["message"] or "")
            author = _markdown_table_cell(row["author"] or "")
            date = (row["committed_at"] or "")[:10]
            files = row["files_changed"]
            if not files:
                try:
                    file_list = json.loads(row.get("files") or "[]")
                except (json.JSONDecodeError, TypeError, AttributeError):
                    file_list = []
                files = len(file_list)
            context = (
                f"I#{row['iteration_id']}"
                if row.get("iteration_id") is not None
                else "история"
            )
            content += (
                f"| {sha_short} | {msg} | {author} | "
                f"{_markdown_table_cell(date)} | {_markdown_table_cell(context)} | "
                f"{_markdown_table_cell(files)} |\n"
            )

        _safe_write(path, content)

    def sync_summary(self) -> None:
        """Write the narrative summary file with stats and key decisions.

        The content comes from templates and real DB data, with no AI
        generation. It includes counters of decisions, commits and
        iterations, and lists the most relevant active decisions.
        """
        path = os.path.join(self._memory_dir, "alfred-summary.md")
        stats = self._db.get_stats()

        total_decisions = stats.get("total_decisions", 0)
        total_commits = stats.get("total_commits", 0)
        total_iterations = stats.get("total_iterations", 0)
        linked_commits = self._db._conn.execute(
            "SELECT COUNT(*) FROM commits WHERE iteration_id IS NOT NULL"
        ).fetchone()[0]
        historical_commits = max(0, total_commits - linked_commits)

        # Count active vs archived decisions
        active_decisions = list(
            self._db.iter_decisions(status="active", batch_size=500)
        )
        n_active = len(active_decisions)
        n_archived = total_decisions - n_active

        content = _frontmatter(
            name="Сводка проекта (Alfred)",
            description=(
                "Текущее состояние проекта: статистика "
                "и ключевые решения"
            ),
        )

        content += f"\nАктивных решений в проекте: {n_active}"
        if n_archived > 0:
            content += f", архивных: {n_archived}"
        content += ".\n"

        # Active iteration
        active_iter = self._db.get_active_iteration()
        if active_iter:
            cmd = active_iter.get("command", "?")
            desc = active_iter.get("description", "")
            content += f'Текущая итерация: "{cmd}: {desc}".\n'

        content += (
            f"Commits, связанных с итерациями: {linked_commits} "
            f"(итераций: {total_iterations}).\n"
        )
        if historical_commits:
            content += (
                f"Импортированных commits в истории для справки: {historical_commits}.\n"
            )

        # Key decisions (up to 10)
        if active_decisions:
            content += "\n### Действующие ключевые решения\n\n"
            for d in active_decisions[:10]:
                title = d.get("title", "без названия")
                chosen = _single_line_text(d.get("chosen", ""))
                if len(chosen) > 80:
                    chosen = chosen[:77] + "..."
                content += f"- **D#{d['id']} -- {title}:** {chosen}\n"

        _safe_write(path, content)

    # --- Index management ----------------------------------------------------

    def update_index(self) -> None:
        """
        Update the delimited section of MEMORY.md.

        Finds the ``ALFRED-SYNC:START/END`` markers in MEMORY.md and rewrites
        only the content between them. If they do not exist, adds them at the
        end of the file. If MEMORY.md does not exist, creates it with the
        Alfred section.
        """
        memory_md = os.path.join(self._memory_dir, "MEMORY.md")

        # Build the sync block
        lines = [_SYNC_START, "## Постоянная память (Alfred)", ""]
        alfred_files = self._list_alfred_files()

        for filename, description in alfred_files:
            lines.append(f"- [{filename}]({filename}) -- {description}")

        lines.append(_SYNC_END)
        sync_block = "\n".join(lines) + "\n"

        # Read the existing MEMORY.md or create a new one
        existing = ""
        if os.path.isfile(memory_md):
            try:
                with open(memory_md, "r", encoding="utf-8") as f:
                    existing = f.read()
            except OSError:
                pass

        start_pos = existing.find(_SYNC_START)
        end_pos = existing.find(_SYNC_END)

        if start_pos != -1 and end_pos != -1 and start_pos < end_pos:
            # Replace the existing block (markers in the correct order)
            updated = (
                existing[:start_pos]
                + sync_block.strip()
                + existing[end_pos + len(_SYNC_END):]
            )
        elif start_pos != -1 or end_pos != -1:
            # Orphan markers or markers in reverse order: remove them and
            # add a clean block at the end to prevent corruption
            cleaned = existing.replace(_SYNC_START, "").replace(_SYNC_END, "")
            updated = cleaned.rstrip() + "\n\n" + sync_block
        elif existing:
            # Add at the end
            updated = existing.rstrip() + "\n\n" + sync_block
        else:
            # MEMORY.md does not exist: create it with the Alfred section
            updated = sync_block

        _safe_write(memory_md, updated)

    # --- Cleanup -------------------------------------------------------------

    def cleanup_stale(self) -> List[str]:
        """
        Delete ``alfred-*.md`` files that no longer match active data.

        Compares the files with the ``alfred-`` prefix on disk with the active
        IDs in SQLite. Deletes only files with ``source: alfred-memory`` in
        the frontmatter, so manual memories stay untouched.

        Returns:
            List of paths of deleted files.
        """
        deleted: List[str] = []
        active_ids = {
            decision["id"]
            for decision in self._db.iter_decisions(
                status="active",
                batch_size=500,
            )
        }

        try:
            entries = os.listdir(self._memory_dir)
        except OSError:
            return deleted

        for entry in entries:
            if not entry.startswith(_FILE_PREFIX):
                continue
            if entry == "MEMORY.md":
                continue

            full_path = os.path.join(self._memory_dir, entry)

            # Touch only files that this module generated
            if not _is_alfred_file(full_path):
                continue

            # Decision files: check if the ID is still active
            if (
                entry.startswith("alfred-decision-")
                and entry != "alfred-decisions-archived.md"
            ):
                try:
                    id_str = entry.replace(
                        "alfred-decision-", ""
                    ).replace(".md", "")
                    decision_id = int(id_str)
                    if decision_id not in active_ids:
                        _safe_delete(full_path)
                        deleted.append(full_path)
                except (ValueError, IndexError):
                    pass
                continue

            # Active iteration file: check if an active iteration exists
            if entry == "alfred-iteration-active.md":
                if self._db.get_active_iteration() is None:
                    _safe_delete(full_path)
                    deleted.append(full_path)

        return deleted

    # --- Private methods ----------------------------------------------------

    def _sync_decisions(self) -> None:
        """Write one file for each active decision."""
        for d in self._db.iter_decisions(status="active", batch_size=500):
            self._write_decision_file(d)

    def _sync_archived(self) -> None:
        """Write the consolidated file of archived decisions."""
        path = os.path.join(
            self._memory_dir, "alfred-decisions-archived.md"
        )

        # Get decisions that are not active
        all_decisions = list(self._db.iter_decisions(batch_size=500))
        archived = [
            d for d in all_decisions if d.get("status") != "active"
        ]

        if not archived:
            _safe_delete(path)
            return

        content = _frontmatter(
            name="Архивные решения Alfred",
            description=(
                "Заменённые или устаревшие решения -- "
                "исторический контекст для справки"
            ),
        )

        for d in archived:
            title = d.get("title", "без названия")
            status = d.get("status", "?")
            chosen = d.get("chosen", "")
            date = (d.get("decided_at") or "")[:10]
            content += f"\n## D#{d['id']} -- {title} ({status})\n\n"
            content += f"**Выбрано:** {chosen}\n"

            # Find a decision that replaces this one
            links = self._db.get_decision_links(d["id"])
            for link in links:
                if (
                    link.get("link_type") == "supersedes"
                    and link.get("source_id") != d["id"]
                ):
                    content += f"**Заменено решением:** D#{link['source_id']}\n"
                    break

            content += f"**Дата:** {date}\n\n---\n"

        _safe_write(path, content)

    def _write_decision_file(self, decision: Dict[str, Any]) -> None:
        """Write one .md file for an active decision."""
        path = self._decision_path(decision["id"])

        impact = decision.get("impact", "")
        phase = decision.get("phase", "")
        chosen = decision.get("chosen", "")

        desc_parts = [chosen]
        if phase:
            desc_parts.append(f"решение фазы {phase}")
        if impact:
            desc_parts.append(f"влияние {impact}")

        content = _frontmatter(
            name=(
                f"D#{decision['id']}: "
                f"{decision.get('title', 'без названия')}"
            ),
            description=" -- ".join(desc_parts),
            source_id=decision["id"],
        )

        # Context
        context = decision.get("context")
        if context:
            content += f"\n## Контекст\n\n{context}\n"

        # Chosen option
        content += f"\n## Выбранный вариант\n\n{chosen}\n"

        # Rejected alternatives
        alt_raw = decision.get("alternatives")
        if alt_raw:
            try:
                alts = (
                    json.loads(alt_raw)
                    if isinstance(alt_raw, str)
                    else alt_raw
                )
                if alts:
                    content += "\n## Отклонённые альтернативы\n\n"
                    for alt in alts:
                        content += f"- {alt}\n"
            except (json.JSONDecodeError, TypeError):
                pass

        # Rationale
        rationale = decision.get("rationale")
        if rationale:
            content += f"\n## Обоснование\n\n{rationale}\n"

        # Metadata on the last line
        tags_raw = decision.get("tags", "[]")
        try:
            tags = (
                json.loads(tags_raw)
                if isinstance(tags_raw, str)
                else tags_raw
            )
            tags_str = ", ".join(tags) if tags else ""
        except (json.JSONDecodeError, TypeError):
            tags_str = ""

        date = (decision.get("decided_at") or "")[:10]
        meta_parts: List[str] = []
        if impact:
            meta_parts.append(f"**Влияние:** {impact}")
        if phase:
            meta_parts.append(f"**Фаза:** {phase}")
        if tags_str:
            meta_parts.append(f"**Теги:** {tags_str}")
        meta_parts.append(f"**Дата:** {date}")

        content += "\n" + " | ".join(meta_parts) + "\n"

        _safe_write(path, content)

    def _decision_path(self, decision_id: int) -> str:
        """Return the path of the .md file for a decision."""
        return os.path.join(
            self._memory_dir, f"alfred-decision-{decision_id}.md"
        )

    def _list_alfred_files(self) -> List[Tuple[str, str]]:
        """
        List the alfred-*.md files with their description for the index.

        Returns:
            List of ``(file_name, description)`` tuples in this order:
            summary first, iteration, decisions, commits, archive.
        """
        result: List[Tuple[str, str]] = []

        # Fixed order for known files
        order = [
            ("alfred-summary.md", "текущее состояние проекта"),
            ("alfred-iteration-active.md", "текущая итерация"),
        ]

        for filename, desc in order:
            if os.path.isfile(os.path.join(self._memory_dir, filename)):
                result.append((filename, desc))

        # Active decisions (sorted by file name)
        try:
            def _decision_sort_key(entry: str) -> tuple[int, str]:
                match = re.match(r"alfred-decision-(\d+)\.md$", entry)
                if match:
                    return (int(match.group(1)), entry)
                return (sys.maxsize, entry)

            for entry in sorted(os.listdir(self._memory_dir), key=_decision_sort_key):
                if (
                    entry.startswith("alfred-decision-")
                    and entry != "alfred-decisions-archived.md"
                ):
                    full = os.path.join(self._memory_dir, entry)
                    title = _read_frontmatter_field(full, "name") or entry
                    result.append((entry, title))
        except OSError:
            pass

        # Recent commits
        commits_file = "alfred-commits-recent.md"
        if os.path.isfile(os.path.join(self._memory_dir, commits_file)):
            result.append((commits_file, "последние commits"))

        # Decision archive
        archived_file = "alfred-decisions-archived.md"
        if os.path.isfile(os.path.join(self._memory_dir, archived_file)):
            n = _count_archived(
                os.path.join(self._memory_dir, archived_file)
            )
            result.append((archived_file, f"исторических решений: {n}"))

        return result


